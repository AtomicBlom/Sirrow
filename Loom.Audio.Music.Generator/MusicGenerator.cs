using System.Collections.Immutable;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Loom.Audio.Music.Generator;

/// <summary>
/// Turns a project's music files into C#: every <c>*.patch.json</c> a property of its patches' class (one part,
/// <c>Patches.g.cs</c>), every <c>*.song.json</c> a class of its own named for the file, in the namespace of its folder.
/// What a file says that can't be code is an error at its place in the file.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class MusicGenerator : IIncrementalGenerator
{
	internal static readonly DiagnosticDescriptor Problem = new(
		"LOOMMUSIC001", "A music file the generator can't make into code", "{0}", "Loom.Music", DiagnosticSeverity.Error, isEnabledByDefault: true);

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var files = context.AdditionalTextsProvider
			.Where(t => t.Path.EndsWith(".patch.json", StringComparison.OrdinalIgnoreCase) || t.Path.EndsWith(".song.json", StringComparison.OrdinalIgnoreCase))
			.Select((t, cancel) => (t.Path, Text: t.GetText(cancel)))
			.Collect();
		var options = context.AnalyzerConfigOptionsProvider.Combine(context.CompilationProvider)
			.Select((pair, _) => MusicOptions.From(pair.Left.GlobalOptions, pair.Right.AssemblyName ?? "Music"));
		context.RegisterSourceOutput(files.Combine(context.CompilationProvider).Combine(options),
			(output, input) => Emit(output, input.Left.Left, input.Left.Right, input.Right));
	}

	private static void Emit(SourceProductionContext output, ImmutableArray<(string Path, SourceText? Text)> files, Compilation compilation, MusicOptions options)
	{
		var patchFiles = files.Where(f => f.Path.EndsWith(".patch.json", StringComparison.OrdinalIgnoreCase))
			.OrderBy(f => Path.GetFileName(f.Path), StringComparer.Ordinal).ToArray();
		var context = new MusicContext(compilation, options, [.. patchFiles.Select(f => SongEmitter.StemOf(f.Path))]);

		if (patchFiles.Length > 0)
		{
			var patches = new PatchEmitter(context);
			var members = new List<string>();
			foreach (var (path, text) in patchFiles)
			{
				if (Read(output, path, text) is not { } root)
					continue;
				try
				{
					// The property is named for the file, which is how songs and the catalog name the patch
					members.Add(string.Join("\n", patches.Property(root, context.PatchProperty(SongEmitter.StemOf(path)), "    ")));
				}
				catch (JsonError error)
				{
					Report(output, path, text!, error);
				}
			}
			var source = new StringBuilder();
			source.AppendLine("// <auto-generated/>");
			source.AppendLine("// Made from the project's *.patch.json files by Loom's music generator: edit those, or make a patch code (\"code\")");
			source.AppendLine("#nullable enable");
			source.AppendLine("using Loom.Audio.Synth.Chip;");
			source.AppendLine("using Loom.Audio.Synth.Dsp;");
			source.AppendLine();
			source.AppendLine($"namespace {options.RootNamespace};");
			source.AppendLine();
			source.AppendLine($"static partial class {options.Patches}");
			source.AppendLine("{");
			source.AppendLine(string.Join("\n\n", members));
			source.AppendLine("}");
			output.AddSource($"{options.Patches}.g.cs", source.ToString().Replace("\r\n", "\n"));
		}

		var songs = new SongEmitter(context);
		foreach (var (path, text) in files.Where(f => f.Path.EndsWith(".song.json", StringComparison.OrdinalIgnoreCase)))
		{
			if (Read(output, path, text) is not { } root)
				continue;
			try
			{
				var source = songs.Class(root, Path.GetFileName(path), options.NamespaceOf(path));
				output.AddSource($"{Code.Identifier(Code.Pascal(SongEmitter.StemOf(path)))}.g.cs", source.Replace("\r\n", "\n"));
			}
			catch (JsonError error)
			{
				Report(output, path, text!, error);
			}
		}
	}

	private static Json? Read(SourceProductionContext output, string path, SourceText? text)
	{
		if (text is null)
			return null;
		try
		{
			var root = Json.Parse(text.ToString());
			var format = root["format"]?.Str;
			var expected = path.EndsWith(".patch.json", StringComparison.OrdinalIgnoreCase) ? "loom-patch/1" : "loom-song/2";
			if (format != expected)
				throw new JsonError($"{Path.GetFileName(path)} says \"format\": \"{format}\"; the generator reads \"{expected}\""
					+ (format == "loom-song/1" ? " (move the song-wide \"order\" or \"conduct\" into each section's \"exits\", then set the format)" : ""),
					root["format"]?.Span ?? new TextSpan(0, 0));
			return root;
		}
		catch (JsonError error)
		{
			Report(output, path, text, error);
			return null;
		}
	}

	private static void Report(SourceProductionContext output, string path, SourceText text, JsonError error)
	{
		var span = new TextSpan(Math.Min(error.Span.Start, text.Length), Math.Min(error.Span.Length, Math.Max(0, text.Length - error.Span.Start)));
		var location = Location.Create(path, span, text.Lines.GetLinePositionSpan(span));
		output.ReportDiagnostic(Diagnostic.Create(Problem, location, $"{Path.GetFileName(path)}: {error.Message}"));
	}
}

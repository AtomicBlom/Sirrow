namespace BinaryVibrance.Sirrow.Synth.Music;

/// <summary>A pitch class, the twelve notes of the octave from C, sharps for the black keys.</summary>
public enum Note
{
	/// <summary>C, pitch class 0.</summary>
	C,
	/// <summary>C sharp (D flat), 1.</summary>
	Cs,
	/// <summary>D, 2.</summary>
	D,
	/// <summary>D sharp (E flat), 3.</summary>
	Ds,
	/// <summary>E, 4.</summary>
	E,
	/// <summary>F, 5.</summary>
	F,
	/// <summary>F sharp (G flat), 6.</summary>
	Fs,
	/// <summary>G, 7.</summary>
	G,
	/// <summary>G sharp (A flat), 8.</summary>
	Gs,
	/// <summary>A, 9.</summary>
	A,
	/// <summary>A sharp (B flat), 10.</summary>
	As,
	/// <summary>B, 11.</summary>
	B,
}
